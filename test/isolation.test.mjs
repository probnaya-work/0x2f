import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { git, captureTree, treeDiff, prepareWorkspace } from '../src/core/isolation.mjs';
import { createRuntime } from '../src/runtime.mjs';
const pause = ms => new Promise(r=>setTimeout(r,ms));
async function until(fn) { const end=Date.now()+15000; while(Date.now()<end){const v=await fn();if(v)return v;await pause(25);}throw new Error('timeout'); }
async function repo(t) {
  const base=await fs.mkdtemp(path.join(os.tmpdir(),'2f-isolate-'));
  t.after(()=>fs.rm(base,{recursive:true,force:true}));
  await git(base,['init']);
  await fs.writeFile(path.join(base,'seed.txt'),'before\n');
  await fs.writeFile(path.join(base,'.gitignore'),'.work/\n');
  await git(base,['add','.']);
  await git(base,['-c','user.name=fixture','-c','user.email=fixture@example.invalid','commit','-m','seed']);
  return base;
}
test('private snapshots observe same-status dirty edits, binary and symlink content without changing the index',async t=>{
  const base=await repo(t), evidence=path.join(base,'.work/evidence');
  await fs.writeFile(path.join(base,'seed.txt'),'dirty before\n');
  const indexBefore=await git(base,['diff','--cached','--binary']);
  const before=await captureTree(base,evidence);
  await fs.writeFile(path.join(base,'seed.txt'),'dirty after\n');
  await fs.writeFile(path.join(base,'binary'),Buffer.from([0,1,2,3]));
  await fs.symlink('/outside/not-read',path.join(base,'link'));
  await fs.writeFile(path.join(base,'quoted " path\nname'),'quoted');
  const after=await captureTree(base,evidence);
  const diff=await treeDiff(base,evidence,before,after);
  assert.match(diff.patch,/-dirty before\n\+dirty after/);
  assert.match(diff.patch,/GIT binary patch/);
  assert.match(diff.patch,/outside\/not-read/);
  assert.ok(diff.files.includes('quoted " path\nname'));
  assert.equal(await git(base,['diff','--cached','--binary']),indexBefore);
  await fs.writeFile(path.join(base,'seed.txt'),'later external edit');
  assert.equal((await treeDiff(base,evidence,before,after)).patch,diff.patch);
});
test('dirty automatic isolation refuses, explicit isolated starts from HEAD and leaves dirty bytes intact',async t=>{
  const base=await repo(t);
  await fs.writeFile(path.join(base,'seed.txt'),'human dirty');
  await fs.writeFile(path.join(base,'human-untracked'),'keep');
  await assert.rejects(()=>prepareWorkspace(base,{slug:'001-test'}),/existing changes/);
  const ws=await prepareWorkspace(base,{slug:'001-test'},'isolated');
  assert.equal(await fs.readFile(path.join(ws.path,'seed.txt'),'utf8'),'before\n');
  assert.equal(await fs.readFile(path.join(base,'seed.txt'),'utf8'),'human dirty');
  assert.equal(await fs.readFile(path.join(base,'human-untracked'),'utf8'),'keep');
  assert.equal(ws.originalDirty,true);
});
test('two isolated tasks, immutable run changes, conflict-safe apply and archived cleanup',async t=>{
  const base=await repo(t);
  await fs.mkdir(path.join(base,'.work/providers'),{recursive:true});
  const script=path.join(base,'.work','writer.mjs');
  await fs.writeFile(script,`import fs from 'node:fs';fs.writeFileSync('seed.txt','agent change\\n');fs.writeFileSync('new.bin',Buffer.from([0,4,5]));console.log('done');`);
  await fs.writeFile(path.join(base,'.work/providers/fixture.json'),JSON.stringify({id:'fixture',displayName:'fixture',transport:'command',command:[process.execPath,script,'{prompt}']}));
  const rt=createRuntime(base);
  const tasks=await Promise.all([1,2].map(n=>rt.actions.createWork({brief:'isolated task '+n,provider:'fixture'})));
  for(const task of tasks) await until(async()=> (await rt.store.findTask(task.id)).status==='ready');
  assert.notEqual(tasks[0].checkout.path,tasks[1].checkout.path);
  assert.equal(await fs.readFile(path.join(base,'seed.txt'),'utf8'),'before\n');
  const saved=await rt.actions.getRunChanges(tasks[0].id,1);
  assert.match(saved.patch,/agent change/);
  await fs.writeFile(path.join(base,'seed.txt'),'human conflict\n');
  await assert.rejects(()=>rt.actions.applyWork(tasks[0].id),/Git workspace operation failed/);
  assert.equal(await fs.readFile(path.join(base,'seed.txt'),'utf8'),'human conflict\n');
  await assert.rejects(fs.access(path.join(base,'new.bin')));
  await fs.writeFile(path.join(base,'seed.txt'),'before\n');
  await rt.actions.applyWork(tasks[0].id);
  assert.equal(await fs.readFile(path.join(base,'seed.txt'),'utf8'),'agent change\n');
  await fs.writeFile(path.join(tasks[0].checkout.path,'seed.txt'),'later edit\n');
  assert.equal((await rt.actions.getRunChanges(tasks[0].id,1)).patch,saved.patch);
  const archived=await rt.actions.cleanupWork(tasks[0].id);
  assert.ok(archived.checkout.archiveSha256);
  await assert.rejects(fs.access(tasks[0].checkout.path));
  assert.ok((await fs.stat(path.join(rt.store.taskDir(tasks[0].slug),'workspace.tar'))).size>0);
});
test('explicit shared mode serializes two independent local tasks',async t=>{
  const base=await repo(t);
  await fs.mkdir(path.join(base,'.work/providers'),{recursive:true});
  const script=path.join(base,'.work','waiting.mjs');
  await fs.writeFile(script,`setInterval(()=>{},1000)`);
  await fs.writeFile(path.join(base,'.work/providers/fixture.json'),JSON.stringify({id:'fixture',displayName:'fixture',transport:'command',command:[process.execPath,script,'{prompt}']}));
  const rt=createRuntime(base);
  const task=await rt.actions.createWork({brief:'shared owner',provider:'fixture',workspaceMode:'shared'});
  await assert.rejects(()=>rt.actions.createWork({brief:'shared contender',provider:'fixture',workspaceMode:'shared'}),/owned by task/);
  await rt.actions.cancelWork(task.id);
  await until(async()=> (await rt.store.findTask(task.id)).status==='failed');
  await pause(600);
});
